function roundedPrice(value: number) {
  return Number(value.toFixed(2))
}

export const lifecareProducts: LifecareProductSeed[] = rawProducts.map(
  (
    [
      sku,
      name,
      category,
      unit,
      costPrice,
      sellingPrice,
      openingStock,
      reorderLevel,
    ],
    index,
  ) => {
    const resolvedSellingPrice = sellingPrice ?? 20
    const resolvedCostPrice =
      costPrice ?? roundedPrice(resolvedSellingPrice * 0.7)
    return {
      sku,
      name,
      category,
      unit,
      costPrice: resolvedCostPrice,
      sellingPrice: resolvedSellingPrice,
      openingStock,
      reorderLevel,
      vatRate: 0,
      barcode: `616${String(2609200000 + index).padStart(10, "0")}`,
      emoji: categoryEmoji[category] ?? "📦",
    }
  },
)
